# Flood Escape 2D - Project Structure

## Assets/_Project/
- **Scripts/**: All C# source code organized by functionality
- **Scenes/**: All Unity scenes (menu, levels, core systems)
- **Prefabs/**: Reusable game objects
- **Sprites/**: All 2D art assets
- **Audio/**: Sound and music files
- **Data/**: Level configurations and scriptable objects
- **Materials/**: Material assets for rendering
- **Shaders/**: Custom shader code
- **Resources/**: Dynamically loaded assets

## Plugins/
- External libraries (SQLite, etc.)

## StreamingAssets/
- Files that need to be read at runtime (database files)
